"""Offline tests: the Apify API is faked. Run: python tests/test_offline.py"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
os.environ['APIFY_TOKEN'] = 'test'

import youtube_transcript_unblocked as m
from youtube_transcript_api._errors import (AgeRestricted, NoTranscriptFound, TranscriptsDisabled,
                                            VideoUnavailable)
from youtube_transcript_api.formatters import SRTFormatter

OK = {'videoId': 'UF8uR6Z6KLc', 'language': 'en', 'languageName': 'English', 'isAutoGenerated': False,
      'segments': [{'start': 7.47, 'duration': 2.899, 'text': 'This program'}, {'start': 10.47, 'duration': 3.973,
                                                                                 'text': 'Please visit'}],
      'availableLanguages': [{'language': 'en', 'name': 'English', 'isAutoGenerated': False}], 'error': None}
ROWS = {
    'UF8uR6Z6KLc': OK,
    'nocaps11111': {'videoId': 'nocaps11111', 'error': 'This video has no captions (neither uploaded nor auto-generated)'},
    'gone1111111': {'videoId': 'gone1111111', 'error': 'Video unavailable: This video is private'},
    'age11111111': {'videoId': 'age11111111', 'error': 'Age-restricted video: YouTube only shows it to signed-in users'},
    'german11111': {'videoId': 'german11111', 'error': 'No en captions. Available: de, de (auto)'},
}
calls = []


def fake_call(self, run_input):
    calls.append(run_input)
    return [ROWS[v] for v in run_input['urls']]


m.YouTubeTranscriptApi._call = fake_call


def test_fetch():
    t = m.YouTubeTranscriptApi().fetch('https://www.youtube.com/watch?v=UF8uR6Z6KLc')
    assert isinstance(t, m.FetchedTranscript) and len(t) == 2 and t[0].text == 'This program'
    assert t.to_raw_data()[1] == {'text': 'Please visit', 'start': 10.47, 'duration': 3.973}
    assert t.language_code == 'en' and not t.is_generated
    assert '00:00:07,470' in SRTFormatter().format_transcript(t)
    assert calls[-1]['urls'] == ['UF8uR6Z6KLc'] and calls[-1]['languages'] == ['en']


def test_errors_are_the_original_classes():
    api = m.YouTubeTranscriptApi()
    for vid, cls in [('nocaps11111', TranscriptsDisabled), ('gone1111111', VideoUnavailable),
                     ('age11111111', AgeRestricted), ('german11111', NoTranscriptFound)]:
        try:
            api.fetch(vid)
            raise AssertionError(vid)
        except cls as e:
            assert e.video_id == vid
            str(e)  # message builds


def test_fetch_many_and_legacy():
    out = m.YouTubeTranscriptApi().fetch_many(['UF8uR6Z6KLc', 'nocaps11111'])
    assert len(calls[-1]['urls']) == 2
    assert isinstance(out['UF8uR6Z6KLc'], m.FetchedTranscript) and isinstance(out['nocaps11111'], TranscriptsDisabled)
    got, failed = m.YouTubeTranscriptApi.get_transcripts(['UF8uR6Z6KLc', 'nocaps11111'], continue_after_error=True)
    assert failed == ['nocaps11111'] and got['UF8uR6Z6KLc'][0]['text'] == 'This program'
    assert m.YouTubeTranscriptApi.get_transcript('UF8uR6Z6KLc')[0]['start'] == 7.47


def test_list():
    tracks = m.YouTubeTranscriptApi().list('UF8uR6Z6KLc')
    assert tracks[0].language_code == 'en' and tracks[0].fetch()[0].text == 'This program'


def test_no_token():
    old = os.environ.pop('APIFY_TOKEN')
    try:
        m.YouTubeTranscriptApi()
        raise AssertionError
    except m.ApifyError as e:
        assert 'sign-up' in str(e)
    finally:
        os.environ['APIFY_TOKEN'] = old


